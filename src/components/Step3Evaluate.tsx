import React, { useState, useEffect } from 'react';
import {
  Sparkles,
  CheckCircle2,
  AlertTriangle,
  XCircle,
  HelpCircle,
  Copy,
  Check,
  RotateCcw,
  AlertCircle,
  ArrowLeft,
  FileCheck2,
  Layers,
  ChevronDown,
  ChevronUp,
  SlidersHorizontal,
} from 'lucide-react';
import { Criterion, EvaluationResult, CriterionEvaluation } from '../types';

interface Step3EvaluateProps {
  criteria: Criterion[];
  notes: string;
  imageBase64: string | null;
  imageMimeType: string | null;
  imageFileName: string | null;
  evaluationResult: EvaluationResult | null;
  setEvaluationResult: (res: EvaluationResult | null) => void;
  onBackToDesign: () => void;
  onBackToResearch: () => void;
}

export const Step3Evaluate: React.FC<Step3EvaluateProps> = ({
  criteria,
  notes,
  imageBase64,
  imageMimeType,
  imageFileName,
  evaluationResult,
  setEvaluationResult,
  onBackToDesign,
  onBackToResearch,
}) => {
  const [isEvaluating, setIsEvaluating] = useState(false);
  const [evalError, setEvalError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const [activeFilter, setActiveFilter] = useState<'All' | 'Addressed' | 'Partly addressed' | 'Needs attention' | 'Insufficient information'>('All');
  const [expandedCriteria, setExpandedCriteria] = useState<Record<string, boolean>>({});

  const approvedCriteria = criteria.filter((c) => c.approved);

  const runEvaluation = async () => {
    if (approvedCriteria.length === 0) {
      setEvalError('Please approve at least one criterion in Step 1 before evaluating.');
      return;
    }

    setIsEvaluating(true);
    setEvalError(null);

    try {
      const response = await fetch('/api/evaluate-design', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          criteria: approvedCriteria,
          notes,
          imageBase64,
          imageMimeType,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error || 'Evaluation request failed.');
      }

      setEvaluationResult(data);
    } catch (err: any) {
      console.error('Evaluation error:', err);
      setEvalError(err.message || 'An unexpected error occurred during evaluation.');
    } finally {
      setIsEvaluating(false);
    }
  };

  // If no evaluation yet and criteria are available, trigger or prompt evaluation
  useEffect(() => {
    if (!evaluationResult && approvedCriteria.length > 0 && !isEvaluating && !evalError) {
      runEvaluation();
    }
  }, []);

  const handleCopyResults = () => {
    if (!evaluationResult) return;

    const timestamp = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });

    let report = `# NeuroDesign — Lighting Design Evaluation Report
Generated: ${timestamp}
Evaluated against ${approvedCriteria.length} user-supplied research criteria.
Overall Alignment Score: ${evaluationResult.overallAlignmentScore}/100

## Executive Summary
${evaluationResult.executiveSummary}

## Key Strengths
${evaluationResult.keyStrengths?.map((s) => `- ${s}`).join('\n') || 'None recorded'}

## Priority Adjustments
${evaluationResult.priorityAdjustments?.map((a) => `- ${a}`).join('\n') || 'None recorded'}

---
## Detailed Criteria Breakdown

`;

    evaluationResult.evaluations.forEach((item, index) => {
      report += `### ${index + 1}. ${item.criterionTitle}
- Status: ${item.status.toUpperCase()}
- Design Evidence: ${item.designEvidence}
- Research Grounding: ${item.researchGrounding}
- Practical Improvement: ${item.practicalImprovement}
${item.missingSpecifications ? `- Missing Specifications: ${item.missingSpecifications}\n` : ''}
`;
    });

    report += `\n---\n*Report generated by NeuroDesign utilizing Gemini architectural lighting models.*`;

    navigator.clipboard.writeText(report).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 3000);
    });
  };

  const getStatusBadge = (status: CriterionEvaluation['status']) => {
    switch (status) {
      case 'Addressed':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-teal-100 text-teal-800 border border-teal-300">
            <CheckCircle2 className="w-3.5 h-3.5 text-teal-700" />
            Addressed
          </span>
        );
      case 'Partly addressed':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-amber-100 text-amber-900 border border-amber-300">
            <AlertTriangle className="w-3.5 h-3.5 text-amber-700" />
            Partly addressed
          </span>
        );
      case 'Needs attention':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-rose-100 text-rose-900 border border-rose-300">
            <XCircle className="w-3.5 h-3.5 text-rose-700" />
            Needs attention
          </span>
        );
      case 'Insufficient information':
      default:
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-stone-200 text-stone-800 border border-stone-300">
            <HelpCircle className="w-3.5 h-3.5 text-stone-600" />
            Insufficient information
          </span>
        );
    }
  };

  const filteredEvaluations = evaluationResult?.evaluations.filter((item) => {
    if (activeFilter === 'All') return true;
    return item.status === activeFilter;
  }) || [];

  const statusCounts = {
    Addressed: evaluationResult?.evaluations.filter((e) => e.status === 'Addressed').length || 0,
    'Partly addressed': evaluationResult?.evaluations.filter((e) => e.status === 'Partly addressed').length || 0,
    'Needs attention': evaluationResult?.evaluations.filter((e) => e.status === 'Needs attention').length || 0,
    'Insufficient information': evaluationResult?.evaluations.filter((e) => e.status === 'Insufficient information').length || 0,
  };

  return (
    <div className="space-y-8 animate-in fade-in duration-300">
      {/* Intro Header & Action Bar */}
      <div className="bg-[#FFFFFF] border border-[#E8E2D8] rounded-2xl p-6 sm:p-8 shadow-xs">
        <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6">
          <div className="max-w-3xl">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-teal-50 border border-teal-200 text-teal-800 text-xs font-semibold mb-3">
              <FileCheck2 className="w-3.5 h-3.5" />
              Step 3: Neuro-Architecture Lighting Evaluation
            </div>
            <h1 className="text-3xl sm:text-4xl font-bold font-display text-stone-900 tracking-tight">
              Evidence-Based Design Evaluation
            </h1>
            <p className="mt-2 text-base text-stone-600 leading-relaxed">
              Gemini has rigorously cross-referenced your lighting plan and explanatory notes against each
              approved research criterion. Review findings, identified evidence, practical improvements,
              and requests for missing technical photometrics.
            </p>
          </div>

          <div className="flex flex-wrap items-center gap-3 shrink-0">
            {evaluationResult && (
              <button
                type="button"
                onClick={handleCopyResults}
                className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-teal-800 hover:bg-teal-900 text-white font-medium text-sm shadow-sm transition-all"
              >
                {copied ? (
                  <>
                    <Check className="w-4 h-4 text-emerald-300" />
                    Copied to Clipboard!
                  </>
                ) : (
                  <>
                    <Copy className="w-4 h-4 text-teal-200" />
                    Copy Results
                  </>
                )}
              </button>
            )}

            <button
              type="button"
              onClick={runEvaluation}
              disabled={isEvaluating}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl border border-[#D5CDC2] hover:bg-[#F5F2EB] text-stone-700 font-medium text-sm transition-colors"
            >
              <RotateCcw className={`w-4 h-4 ${isEvaluating ? 'animate-spin' : ''}`} />
              Re-Evaluate
            </button>
          </div>
        </div>
      </div>

      {/* Evaluating Progress State */}
      {isEvaluating && (
        <div className="bg-[#FFFFFF] border border-teal-700/30 rounded-2xl p-12 text-center shadow-md animate-pulse">
          <div className="w-16 h-16 rounded-2xl bg-teal-50 border border-teal-200 text-teal-800 flex items-center justify-center mx-auto mb-4">
            <Sparkles className="w-8 h-8 animate-spin" />
          </div>
          <h3 className="text-xl font-bold font-display text-stone-900">
            Evaluating Lighting Design Against Research Criteria
          </h3>
          <p className="text-sm text-stone-600 mt-2 max-w-md mx-auto">
            Gemini is analyzing visual fixtures, circadian zoning, optical cutoff angles, and explanatory notes...
          </p>
          <div className="mt-6 flex items-center justify-center gap-3 text-xs text-stone-500 font-mono">
            <span>• Inspecting CAD / RCP image</span>
            <span>• Cross-referencing citations</span>
            <span>• Formulating improvements</span>
          </div>
        </div>
      )}

      {/* Error Callout */}
      {evalError && !isEvaluating && (
        <div className="p-6 rounded-2xl bg-rose-50 border border-rose-200 text-rose-900 shadow-xs">
          <div className="flex items-start gap-4">
            <AlertCircle className="w-6 h-6 text-rose-600 shrink-0 mt-0.5" />
            <div className="space-y-2">
              <h3 className="text-base font-bold font-display text-rose-950">
                Evaluation Request Failed
              </h3>
              <p className="text-sm text-rose-800 leading-relaxed">
                {evalError}
              </p>
              <p className="text-xs text-rose-700">
                If quota or API configuration prevents evaluation, check your Gemini API key in Settings &gt; Secrets, or retry in a moment.
              </p>
              <div className="pt-2">
                <button
                  type="button"
                  onClick={runEvaluation}
                  className="px-4 py-2 rounded-lg bg-rose-600 text-white font-medium text-xs hover:bg-rose-700"
                >
                  Retry Evaluation
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Evaluation Dashboard Results */}
      {evaluationResult && !isEvaluating && (
        <div className="space-y-6">
          {/* Top Metric & Executive Summary Cards */}
          <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
            {/* Score & Distribution (4 cols) */}
            <div className="lg:col-span-4 bg-[#FFFFFF] border border-[#E8E2D8] rounded-2xl p-6 shadow-xs flex flex-col justify-between">
              <div>
                <span className="text-xs font-bold text-stone-500 uppercase tracking-wider block">
                  Overall Alignment Score
                </span>
                <div className="mt-4 flex items-baseline gap-3">
                  <span className="text-5xl font-extrabold font-display text-teal-900">
                    {evaluationResult.overallAlignmentScore}
                  </span>
                  <span className="text-lg font-bold text-stone-400">/ 100</span>
                </div>

                <div className="w-full bg-[#EFEAE0] h-3 rounded-full mt-3 overflow-hidden">
                  <div
                    className="h-full bg-teal-800 rounded-full transition-all duration-500"
                    style={{ width: `${Math.min(100, Math.max(0, evaluationResult.overallAlignmentScore))}%` }}
                  />
                </div>

                {/* Status Breakdown Chips */}
                <div className="mt-6 space-y-2 pt-4 border-t border-[#EFEAE0]">
                  <span className="text-xs font-bold text-stone-700 block mb-2">
                    Criteria Status Breakdown:
                  </span>
                  <div className="grid grid-cols-2 gap-2 text-xs">
                    <div className="p-2.5 rounded-lg bg-teal-50 border border-teal-200 flex items-center justify-between">
                      <span className="text-teal-900 font-medium">Addressed</span>
                      <span className="font-bold text-teal-800">{statusCounts.Addressed}</span>
                    </div>
                    <div className="p-2.5 rounded-lg bg-amber-50 border border-amber-200 flex items-center justify-between">
                      <span className="text-amber-900 font-medium">Partly</span>
                      <span className="font-bold text-amber-800">{statusCounts['Partly addressed']}</span>
                    </div>
                    <div className="p-2.5 rounded-lg bg-rose-50 border border-rose-200 flex items-center justify-between">
                      <span className="text-rose-900 font-medium">Attention</span>
                      <span className="font-bold text-rose-800">{statusCounts['Needs attention']}</span>
                    </div>
                    <div className="p-2.5 rounded-lg bg-stone-100 border border-stone-300 flex items-center justify-between">
                      <span className="text-stone-800 font-medium">Insufficient</span>
                      <span className="font-bold text-stone-700">{statusCounts['Insufficient information']}</span>
                    </div>
                  </div>
                </div>
              </div>

              {/* Design Context Info */}
              <div className="mt-6 pt-4 border-t border-[#EFEAE0] text-xs text-stone-500 flex items-center justify-between">
                <span>Plan: {imageFileName || 'Explanatory Notes only'}</span>
                <span>{approvedCriteria.length} Criteria</span>
              </div>
            </div>

            {/* Executive Summary (8 cols) */}
            <div className="lg:col-span-8 bg-[#FFFFFF] border border-[#E8E2D8] rounded-2xl p-6 sm:p-7 shadow-xs flex flex-col justify-between">
              <div>
                <span className="text-xs font-bold text-stone-500 uppercase tracking-wider block mb-2">
                  Executive Design Synthesis
                </span>
                <p className="text-sm sm:text-base text-stone-800 leading-relaxed font-serif italic">
                  "{evaluationResult.executiveSummary}"
                </p>

                {/* Key Strengths & Priority Adjustments */}
                <div className="mt-6 grid grid-cols-1 md:grid-cols-2 gap-4 pt-4 border-t border-[#EFEAE0]">
                  <div className="bg-[#FAF8F5] p-4 rounded-xl border border-[#EDE7DD]">
                    <div className="flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-teal-800 mb-2">
                      <CheckCircle2 className="w-3.5 h-3.5" />
                      Key Design Strengths
                    </div>
                    <ul className="space-y-1.5 text-xs text-stone-700">
                      {evaluationResult.keyStrengths?.map((strength, i) => (
                        <li key={i} className="flex items-start gap-1.5">
                          <span className="text-teal-700 font-bold shrink-0">•</span>
                          <span>{strength}</span>
                        </li>
                      ))}
                    </ul>
                  </div>

                  <div className="bg-[#FAF8F5] p-4 rounded-xl border border-[#EDE7DD]">
                    <div className="flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-rose-800 mb-2">
                      <AlertTriangle className="w-3.5 h-3.5" />
                      Priority Adjustments
                    </div>
                    <ul className="space-y-1.5 text-xs text-stone-700">
                      {evaluationResult.priorityAdjustments?.map((adj, i) => (
                        <li key={i} className="flex items-start gap-1.5">
                          <span className="text-rose-600 font-bold shrink-0">•</span>
                          <span>{adj}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                </div>
              </div>
            </div>
          </div>

          {/* Criteria Evaluation List Header with Filters */}
          <div className="bg-[#FFFFFF] border border-[#E8E2D8] p-4 rounded-2xl shadow-xs flex flex-col sm:flex-row items-center justify-between gap-3">
            <div className="flex items-center gap-2">
              <SlidersHorizontal className="w-4 h-4 text-stone-500" />
              <span className="text-sm font-bold text-stone-800">
                Detailed Criteria Findings ({filteredEvaluations.length})
              </span>
            </div>

            {/* Filter buttons */}
            <div className="flex items-center gap-1.5 flex-wrap">
              {(['All', 'Addressed', 'Partly addressed', 'Needs attention', 'Insufficient information'] as const).map(
                (filter) => (
                  <button
                    key={filter}
                    type="button"
                    onClick={() => setActiveFilter(filter)}
                    className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${
                      activeFilter === filter
                        ? 'bg-teal-800 text-white shadow-xs'
                        : 'bg-[#F5F2EB] text-stone-600 hover:text-stone-900 hover:bg-[#EAE4D9]'
                    }`}
                  >
                    {filter}
                    {filter !== 'All' && ` (${statusCounts[filter]})`}
                  </button>
                )
              )}
            </div>
          </div>

          {/* Evaluations Breakdown Cards */}
          <div className="space-y-4">
            {filteredEvaluations.map((item, index) => {
              // Find source from original criteria
              const originalCrit = criteria.find(
                (c) => c.id === item.criterionId || c.title === item.criterionTitle
              );

              return (
                <div
                  key={item.criterionId || index}
                  className="bg-[#FFFFFF] border border-[#E8E2D8] rounded-2xl p-6 shadow-xs transition-all hover:border-[#D5CDC2]"
                >
                  {/* Top Bar: Title, Category & Status */}
                  <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-[#F0ECE1]">
                    <div>
                      {originalCrit?.category && (
                        <span className="text-[11px] font-semibold uppercase tracking-wider text-teal-800 bg-teal-50 px-2 py-0.5 rounded border border-teal-200/60 mb-1.5 inline-block">
                          {originalCrit.category}
                        </span>
                      )}
                      <h3 className="text-lg font-bold font-display text-stone-900">
                        {item.criterionTitle}
                      </h3>
                    </div>

                    <div>
                      {getStatusBadge(item.status)}
                    </div>
                  </div>

                  {/* Body Content Grid */}
                  <div className="mt-4 grid grid-cols-1 md:grid-cols-2 gap-4">
                    {/* Design Evidence */}
                    <div className="p-4 rounded-xl bg-[#FAF8F5] border border-[#EFEAE0]">
                      <span className="text-xs font-bold uppercase tracking-wider text-stone-700 block mb-1.5">
                        Design Evidence (Plan &amp; Notes)
                      </span>
                      <p className="text-xs sm:text-sm text-stone-800 leading-relaxed">
                        {item.designEvidence}
                      </p>
                    </div>

                    {/* Research Grounding */}
                    <div className="p-4 rounded-xl bg-[#FAF8F5] border border-[#EFEAE0]">
                      <span className="text-xs font-bold uppercase tracking-wider text-teal-900 block mb-1.5">
                        Research Citation &amp; Grounding
                      </span>
                      <p className="text-xs sm:text-sm text-stone-800 leading-relaxed italic">
                        {item.researchGrounding}
                      </p>
                    </div>
                  </div>

                  {/* Practical Improvement Recommendation */}
                  <div className="mt-4 p-4 rounded-xl bg-teal-50/70 border border-teal-200/70">
                    <span className="text-xs font-bold uppercase tracking-wider text-teal-900 block mb-1">
                      Practical Interior Design Improvement
                    </span>
                    <p className="text-xs sm:text-sm text-teal-950 leading-relaxed font-medium">
                      {item.practicalImprovement}
                    </p>
                  </div>

                  {/* Missing Specifications Callout (if any) */}
                  {item.missingSpecifications && (
                    <div className="mt-3 p-3.5 rounded-xl bg-amber-50/80 border border-amber-200 text-xs text-amber-950 flex items-start gap-2.5">
                      <HelpCircle className="w-4 h-4 text-amber-700 shrink-0 mt-0.5" />
                      <div>
                        <strong className="font-semibold block text-amber-900">
                          Missing Technical Specifications Requested:
                        </strong>
                        <p className="mt-0.5 text-amber-900 leading-relaxed">
                          {item.missingSpecifications}
                        </p>
                      </div>
                    </div>
                  )}
                </div>
              );
            })}
          </div>

          {/* Bottom Action Footer */}
          <div className="pt-6 border-t border-[#E8E2D8] flex flex-col sm:flex-row items-center justify-between gap-4">
            <div className="flex items-center gap-3">
              <button
                type="button"
                onClick={onBackToDesign}
                className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl border border-[#D5CDC2] hover:bg-[#F5F2EB] text-stone-700 text-sm font-medium transition-colors"
              >
                <ArrowLeft className="w-4 h-4" />
                Modify Design / Notes
              </button>
              <button
                type="button"
                onClick={onBackToResearch}
                className="text-xs text-stone-500 hover:text-stone-800 underline"
              >
                Edit Criteria
              </button>
            </div>

            <button
              type="button"
              onClick={handleCopyResults}
              className="w-full sm:w-auto inline-flex items-center justify-center gap-2 px-6 py-3 rounded-xl bg-teal-800 hover:bg-teal-900 text-white font-medium text-sm shadow-sm transition-all"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-emerald-300" />
                  Copied Report to Clipboard!
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-teal-200" />
                  Copy Evaluation Results
                </>
              )}
            </button>
          </div>
        </div>
      )}
    </div>
  );
};
